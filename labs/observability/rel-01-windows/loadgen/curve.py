"""하루 트래픽 곡선. 시각(0~24시, 실수)을 넣으면 피크 대비 비율(0~1)을 돌려준다.

시간마다 정한 값을 선형으로 잇는다. 새벽 3~4시가 가장 낮고(피크의 6%), 오후 2시가 피크다.
실습 부하 생성기와 1편 계산이 같은 곡선을 쓴다.
"""
HOURLY = [0.25, 0.12, 0.08, 0.06, 0.06, 0.08, 0.15, 0.30, 0.50, 0.70, 0.80, 0.90,
          0.95, 0.90, 1.00, 0.95, 0.90, 0.85, 0.80, 0.85, 0.90, 0.80, 0.60, 0.40]


def ratio(hour):
    hour %= 24
    i = int(hour)
    f = hour - i
    return HOURLY[i] * (1 - f) + HOURLY[(i + 1) % 24] * f
